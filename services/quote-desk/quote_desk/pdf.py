"""Render a quote as a one-page PDF for the fictional provider."""

from __future__ import annotations

from datetime import date, timedelta

from fpdf import FPDF

from . import price_book as pb
from .quote import Needs, Quote

VALID_DAYS = 30
INK = (31, 41, 55)
ACCENT = (37, 99, 235)
MUTED = (107, 114, 128)


def _t(text: str) -> str:
    """The built-in PDF fonts are Latin-1 only; swap the few characters that are not."""
    return (str(text).replace("—", "-").replace("–", "-").replace("·", "-")
            .replace("’", "'").replace("“", '"').replace("”", '"')
            .encode("latin-1", "replace").decode("latin-1"))


def render_pdf(needs: Needs, quote: Quote, number: str, issued: date | None = None) -> bytes:
    issued = issued or date.today()
    pdf = FPDF(format="Letter")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()
    pdf.set_margins(18, 18, 18)

    pdf.set_text_color(*ACCENT)
    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 10, _t(pb.PROVIDER), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(*MUTED)
    pdf.set_font("Helvetica", "", 9)
    pdf.cell(0, 5, "Business internet, phone lines and mobile  |  fictional company for a portfolio demo",
             new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)

    pdf.set_text_color(*INK)
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(0, 8, _t(f"Quote {number}"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(0, 5, _t(f"Issued {issued:%B %d, %Y}  |  valid until {issued + timedelta(days=VALID_DAYS):%B %d, %Y}"),
             new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 5, "Prepared for", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    for line in [needs.company or "Customer", needs.contact_name, needs.contact_email,
                 f"{needs.locations} location(s)" + (f", {needs.staff} staff" if needs.staff else "")]:
        if line:
            pdf.cell(0, 5, _t(line), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)

    widths = (92, 18, 32, 32)
    pdf.set_fill_color(239, 246, 255)
    pdf.set_font("Helvetica", "B", 10)
    for text, w, align in zip(("Service", "Qty", "Unit / month", "Monthly"), widths, "LRRR"):
        pdf.cell(w, 8, text, border="B", align=align, fill=True)
    pdf.ln()
    pdf.set_font("Helvetica", "", 10)
    for line in quote.lines:
        pdf.cell(widths[0], 7, _t(line.description))
        pdf.cell(widths[1], 7, str(line.quantity), align="R")
        pdf.cell(widths[2], 7, f"${line.unit_price:,.2f}", align="R")
        pdf.cell(widths[3], 7, f"${line.monthly:,.2f}", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(sum(widths[:3]), 7, "List price", border="T")
    pdf.cell(widths[3], 7, f"${quote.list_monthly:,.2f}", border="T", align="R", new_x="LMARGIN", new_y="NEXT")
    for adj in quote.adjustments:
        pdf.set_text_color(*(MUTED if adj.amount == 0 else (22, 101, 52)))
        pdf.cell(sum(widths[:3]), 6, _t(adj.label))
        pdf.cell(widths[3], 6, "" if adj.amount == 0 else f"-${-adj.amount:,.2f}", align="R",
                 new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(*INK)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(sum(widths[:3]), 10, f"Monthly total ({pb.CURRENCY}, before tax)", border="T")
    pdf.cell(widths[3], 10, f"${quote.monthly:,.2f}", border="T", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(sum(widths[:3]), 6, "One-time installation")
    pdf.cell(widths[3], 6, f"${quote.one_time:,.2f}", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(sum(widths[:3]), 6, _t(f"Total over the {quote.term_months}-month term"))
    pdf.cell(widths[3], 6, f"${quote.term_total:,.2f}", align="R", new_x="LMARGIN", new_y="NEXT")
    if quote.savings > 0:
        pdf.set_text_color(22, 101, 52)
        pdf.cell(0, 7, _t(f"You save ${quote.savings:,.2f} a month against list price."), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)

    pdf.set_text_color(*MUTED)
    pdf.set_font("Helvetica", "", 8)
    pdf.multi_cell(0, 4, _t(
        f"Prices are monthly in {pb.CURRENCY}, before tax, for a {quote.term_months}-month term. Installation is "
        "booked after signing. This quote is generated by a portfolio demo: Northwind Connect, its products and "
        "its prices are fictional, and this is not an offer."))
    return bytes(pdf.output())
